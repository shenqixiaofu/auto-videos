import uuid


def generate_sql(data_list, gender_text="男孩"):
    table_name = "ai_style_theme"
    sql_template = (
        "INSERT INTO `{table}` "
        "(`uuid`, `theme_name`, `gender`, `material`, `clothing_style`, `colors`, `vibe`, `status`, `created_id`) "
        "VALUES \n{values};"
    )

    value_rows = []
    for item in data_list:
        # 生成 32 位无横杠 UUID
        u_id = uuid.uuid4().hex

        # 处理单引号转义，防止 SQL 报错
        theme = item["theme"].replace("'", "''")
        material = item["material"].replace("'", "''")
        style = item["clothing_style"].replace("'", "''")
        colors = item["colors"].replace("'", "''")
        vibe = item["vibe"].replace("'", "''")

        # 拼接单行数据
        row = (
            f"('{u_id}', '{theme}', '{gender_text}', '{material}', "
            f"'{style}', '{colors}', '{vibe}', 1, 1)"
        )
        value_rows.append(row)

    # 用逗号和换行符连接所有行
    final_sql = sql_template.format(table=table_name, values=",\n".join(value_rows))
    return final_sql


